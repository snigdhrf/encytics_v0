// Bridges the Supabase CLI and Vite: reads the machine-generated local API
// key from `supabase status` and writes .env.development.local (gitignored),
// which Vite loads with higher precedence than the committed .env.development.
//
// Usage:  supabase start   (once, from this folder)
//         npm run setup:local
//
// Works with both key generations: older CLIs report ANON_KEY (a JWT), newer
// ones report a publishable key (sb_publishable_...). supabase-js accepts
// either as the client key.

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function supabaseStatusEnv() {
  // Try a global install first, then the npx wrapper package.
  for (const [cmd, args] of [
    ["supabase", ["status", "-o", "env"]],
    ["npx", ["--yes", "supabase", "status", "-o", "env"]],
  ]) {
    const res = spawnSync(cmd, args, { cwd: appRoot, encoding: "utf8", shell: true });
    if (res.status === 0 && res.stdout) return res.stdout;
  }
  return null;
}

const out = supabaseStatusEnv();
if (!out) {
  console.error(
    "Could not read `supabase status`.\n" +
      "Is the local stack running? Start it first:\n\n" +
      "  supabase start\n\n" +
      "(Install the CLI: https://supabase.com/docs/guides/local-development/cli/getting-started)"
  );
  process.exit(1);
}

// Output is KEY="value" lines; tolerate unquoted values too.
const env = {};
for (const line of out.split(/\r?\n/)) {
  const m = line.match(/^([A-Z0-9_]+)=("?)(.*)\2$/);
  if (m) env[m[1]] = m[3];
}

const url = env.API_URL;
const key = env.ANON_KEY || env.PUBLISHABLE_KEY || env.SB_PUBLISHABLE_KEY;
if (!url || !key) {
  console.error(
    "Unexpected `supabase status -o env` output — found neither ANON_KEY nor a publishable key.\n" +
      `Keys reported: ${Object.keys(env).join(", ") || "(none)"}`
  );
  process.exit(1);
}

const target = path.join(appRoot, ".env.development.local");
writeFileSync(
  target,
  [
    "# Generated by `npm run setup:local` — per-machine local Supabase credentials.",
    "# Gitignored. Re-run the script if `supabase start` ever rotates the key.",
    `VITE_SUPABASE_URL=${url}`,
    `VITE_SUPABASE_ANON_KEY=${key}`,
    "",
  ].join("\n")
);
console.log(`Wrote ${target}`);
console.log(`  VITE_SUPABASE_URL=${url}`);
console.log(`  VITE_SUPABASE_ANON_KEY=${key.slice(0, 12)}… (${key.length} chars)`);
